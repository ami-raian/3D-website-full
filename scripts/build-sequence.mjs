/**
 * Turns a folder of video frames (png/jpg/webp) into a light, web-ready image sequence.
 *
 *   node scripts/build-sequence.mjs <framesDir> [count=144] [portraitFramesDir]
 *
 * - picks `count` evenly spaced frames (the player crossfades between them, so
 *   ~120–180 frames already feel like smooth video)
 * - desktop set: AVIF, up to 1920px wide (the reel is rendered at 1920, so no resampling)
 * - mobile set:  AVIF, up to 1080px wide, from portraitFramesDir if given (e.g. a separate
 *   vertical render), otherwise centre-cropped to 9:16 from the landscape frames
 * - transparency is kept. AVIF because its alpha is compressed lossy: transparent
 *   WebP frames with soft glows came out 3 to 5 times larger
 * - the first frame is also saved as poster.webp, a still image for the rare browser
 *   that can't decode AVIF
 * - writes lib/sequence.ts so the player knows the frame count and sizes
 */
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";

const [, , src, countArg = "144", portraitSrc] = process.argv;
if (!src) {
  console.error("Usage: node scripts/build-sequence.mjs <framesDir> [count] [portraitFramesDir]");
  process.exit(1);
}

const OUT = path.resolve("public/sequence");
const list = async (dir) => {
  const f = (await fs.readdir(dir))
    .filter((n) => /\.(png|jpe?g|webp)$/i.test(n))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  if (!f.length) throw new Error(`No frames found in ${dir}`);
  return f;
};
const files = await list(src);
const pfiles = portraitSrc ? await list(portraitSrc) : null;

const count = Math.min(parseInt(countArg, 10) || 144, files.length, pfiles?.length ?? Infinity);
const spread = (arr) => Array.from({ length: count }, (_, i) => arr[Math.round((i * (arr.length - 1)) / Math.max(1, count - 1))]);
const pick = spread(files);
const ppick = pfiles ? spread(pfiles) : null;

const meta = await sharp(path.join(src, pick[0])).metadata();
const W = meta.width;
const H = meta.height;
const D = { w: Math.min(1920, W) };
D.h = Math.round((D.w * H) / W);

let crop = null;
let M;
if (ppick) {
  const pm = await sharp(path.join(portraitSrc, ppick[0])).metadata();
  M = { w: Math.min(1080, pm.width) };
  M.h = Math.round((M.w * pm.height) / pm.width);
} else {
  const cropW = Math.min(W, Math.round((H * 9) / 16));
  crop = { left: Math.round((W - cropW) / 2), top: 0, width: cropW, height: H };
  M = { w: Math.min(1080, cropW) };
  M.h = Math.round((M.w * H) / cropW);
}

await fs.rm(OUT, { recursive: true, force: true });
await fs.mkdir(path.join(OUT, "d"), { recursive: true });
await fs.mkdir(path.join(OUT, "m"), { recursive: true });

const AVIF_D = { quality: 45, effort: 4, chromaSubsampling: "4:2:0" };
const AVIF_M = { quality: 45, effort: 4, chromaSubsampling: "4:2:0" };
const POSTER = { quality: 72, alphaQuality: 90, effort: 5 };

let bytesD = 0;
let bytesM = 0;
const BATCH = 8;
for (let s = 0; s < count; s += BATCH) {
  await Promise.all(
    pick.slice(s, s + BATCH).map(async (file, k) => {
      const i = s + k;
      const name = `${String(i + 1).padStart(4, "0")}.avif`;
      const dIn = sharp(path.join(src, file)).resize({ width: D.w });
      const mIn = (ppick ? sharp(path.join(portraitSrc, ppick[i])) : sharp(path.join(src, file)).extract(crop)).resize({ width: M.w });
      const d = await dIn.clone().avif(AVIF_D).toFile(path.join(OUT, "d", name));
      const m = await mIn.clone().avif(AVIF_M).toFile(path.join(OUT, "m", name));
      if (i === 0) {
        await dIn.clone().webp(POSTER).toFile(path.join(OUT, "d", "poster.webp"));
        await mIn.clone().webp(POSTER).toFile(path.join(OUT, "m", "poster.webp"));
      }
      bytesD += d.size;
      bytesM += m.size;
    }),
  );
  process.stdout.write(`\r${Math.min(s + BATCH, count)}/${count} frames`);
}

await fs.writeFile(
  path.resolve("lib/sequence.ts"),
  `// Generated by scripts/build-sequence.mjs. Do not edit by hand.
export const SEQUENCE = {
  base: "/sequence",
  ext: "avif",
  count: ${count},
  desktop: { w: ${D.w}, h: ${D.h} },
  mobile: { w: ${M.w}, h: ${M.h} },
} as const;
`,
);

const mb = (b) => (b / 1024 / 1024).toFixed(2) + " MB";
console.log(`\nDesktop set: ${mb(bytesD)} (${D.w}x${D.h})   Mobile set: ${mb(bytesM)} (${M.w}x${M.h})`);
